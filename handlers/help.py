async def help_command(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """نمایش منوی راهنما"""
    text = HELP_MENU_TEXT
    markup = help_menu_keyboard()
    
    if update.callback_query:
        await update.callback_query.answer()
        await update.callback_query.edit_message_text(
            text, reply_markup=markup, parse_mode="Markdown"
        )
    else:
        await update.message.reply_text(
            text, reply_markup=markup, parse_mode="Markdown"
        )


async def help_callback(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """هندلر کلیک روی دکمه‌های راهنما"""
    query = update.callback_query
    await query.answer()
    
    data = query.data
    
    help_pages = {
        "help_quran": QURAN_HELP,
        "help_hadith": HADITH_HELP,
        "help_nahj": NAHJ_HELP,
        "help_mafatih": MAFATIH_HELP,
        "help_quiz": QUIZ_HELP,
        "help_group": GROUP_HELP,
        "help_favorites": FAVORITES_HELP,
        "help_search": SEARCH_HELP,
        "help_admin": ADMIN_HELP,
    }
    
    if data in help_pages:
        text = help_pages[data]
        markup = InlineKeyboardMarkup([
            [InlineKeyboardButton("🔙 بازگشت به راهنما", callback_data="help_back")]
        ])
        await query.edit_message_text(
            text, reply_markup=markup, parse_mode="Markdown"
        )
    elif data == "help_back":
        text = HELP_MENU_TEXT
        markup = help_menu_keyboard()
        await query.edit_message_text(
            text, reply_markup=markup, parse_mode="Markdown"
        )