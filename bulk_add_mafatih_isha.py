def main():
    db.init_db()
    item_id = db.add_mafatih_item(
        category="post_prayers",
        title="تعقیب نماز عشاء",
        arabic_text=ARABIC_TEXT,
        translation_text=None,
        tafsir_text=None,
        slug="isha_post",
    )
    print(f"✅ تعقیب نماز عشاء ثبت شد. id={item_id}, slug=isha_post")
