TARGET_SLUG = "namaz_prophet_friday"

def main():
    db.init_db()
    
    # روش اول: استفاده از ساختار کد پروژه شما
    try:
        item_id = db.add_mafatih_item(
            category="friday_deeds",
            title="نماز حضرت رسول (ص)",
            arabic_text=ARABIC_TEXT,
            translation_text="",
            slug=TARGET_SLUG
        )
        print(f"✅ روش اول موفقیت‌آمیز بود! نماز حضرت رسول ثبت شد (ID: {item_id})")
        return
    except Exception as e:
        print(f"⚠️ روش اول با خطا مواجه شد: {e}")

    # روش دوم: تزریق مستقیم به فایل‌های دیتابیس در صورت لزوم
    print("🔄 در حال تلاش برای ثبت مستقیم در جدول دیتابیس...")
    db_files = ["bot.db", "quran.db", "database.db", "mafatih.db"]
    for db_file in db_files:
        try:
            conn = sqlite3.connect(db_file)
            cursor = conn.cursor()
            
            cursor.execute("PRAGMA table_info(mafatih)")
            columns = [col[1] for col in cursor.fetchall()]
            
            if not columns:
                conn.close()
                continue
            
            # حذف رکورد تکراری احتمالی پیشین
            cursor.execute("DELETE FROM mafatih WHERE slug = ?", (TARGET_SLUG,))
            
            val_map = {
                "category": "friday_deeds",
                "title": "نماز حضرت رسول (ص)",
                "arabic_text": ARABIC_TEXT,
                "translation_text": "",
                "slug": TARGET_SLUG
            }
            
            present_cols = [col for col in val_map.keys() if col in columns]
            placeholders = ", ".join(["?"] * len(present_cols))
            col_names = ", ".join(present_cols)
            values = [val_map[col] for col in present_cols]
            
            query = f"INSERT INTO mafatih ({col_names}) VALUES ({placeholders})"
            cursor.execute(query, values)
            conn.commit()
            conn.close()
            print(f"✅ موفقیت‌آمیز! نماز حضرت رسول با اسلاگ '{TARGET_SLUG}' مستقیماً در دیتابیس '{db_file}' ثبت شد.")
            return
        except sqlite3.OperationalError:
            continue
        except Exception as e:
            print(f"⚠️ تلاش روی دیتابیس '{db_file}' با خطا مواجه شد: {e}")

if __name__ == "__main__":
    main()