def normalize_input_text(text: str) -> str:
    """
    ورودی کاربر (مخصوصاً دستورات ادمین مثل addhadith/addnahj/addmafatih/addquiz)
    را قبل از پارس کردن پاک‌سازی می‌کند تا مشکلات رایج کیبورد موبایل باعث
    شکست تشخیص برچسب‌ها (عربی:، ترجمه: و ...) نشوند. این مشکلات معمولاً شامل:
    - استفاده از حروف عربی بجای معادل فارسی‌شان (ي بجای ی، ك بجای ک)
    - کاراکترهای نامرئی جهت‌ساز/کنترلی که کیبوردهای موبایل گاهی درج می‌کنند
    """
    if not text:
        return text

    # یکسان‌سازی حروف عربی/فارسی که ظاهرشان یکی است ولی کدشان فرق دارد
    replacements = {
        "\u064a": "\u06cc",  # ي عربی -> ی فارسی
        "\u0649": "\u06cc",  # ى (الف مقصوره) -> ی فارسی
        "\u0643": "\u06a9",  # ك عربی -> ک فارسی
        "\u06c0": "\u0647",  # ہ اردو -> ه فارسی
    }
    for src, dst in replacements.items():
        text = text.replace(src, dst)

    # حذف کاراکترهای نامرئی که کیبوردهای موبایل گاهی اضافه می‌کنند
    invisible_chars = ["\u200c", "\u200e", "\u200f", "\u200b", "\ufeff"]
    for ch in invisible_chars:
        text = text.replace(ch, "")

    return text


# جدول تبدیل ارقام لاتین به فارسی، مثلاً 12 -> ۱۲
_PERSIAN_DIGITS = str.maketrans("0123456789", "۰۱۲۳۴۵۶۷۸۹")


def to_persian_digits(value) -> str:
    """
    هر مقدار عددی یا رشته‌ای شامل رقم را برای نمایش به کاربر به رقم فارسی
    تبدیل می‌کند (مثلاً برای شماره‌ی صفحه‌ها، شماره‌ی آیه/حدیث/خطبه و ...).
    این تابع تنها برای *نمایش* استفاده می‌شود؛ در callback_data و منطق
    داخلی همیشه باید از عدد لاتین اصلی استفاده شود.
    """
    return str(value).translate(_PERSIAN_DIGITS)


import re

# اعراب/تشکیل عربی (فتحه، کسره، ضمه، تنوین، شدّ، سکون و مدّ) که در متون مذهبی
# رایج است ولی تقریباً هیچ کاربری هنگام سرچ آن‌ها را تایپ نمی‌کند
_DIACRITICS_RE = re.compile(
    r"[\u0610-\u061A\u064B-\u065F\u0670\u06D6-\u06DC\u06DF-\u06E8\u06EA-\u06ED\u08D4-\u08E1]"
)
_TATWEEL_RE = re.compile(r"\u0640")  # کشیدگی حروف (ـــ)
# هر چیزی غیر از حروف فارسی/عربی، حروف لاتین، عدد و فاصله را حذف می‌کنیم
_PUNCT_RE = re.compile(r"[^\w\s\u0600-\u06FF]", re.UNICODE)
_MULTISPACE_RE = re.compile(r"\s+")


def normalize_for_search(text: str) -> str:
    """
    متن را برای موتور جستجو (چه هنگام ایندکس‌سازی محتوا، چه هنگام پردازش
    عبارتِ سرچِ کاربر) نرمال‌سازی می‌کند. هدف این است که تفاوت‌های ظاهریِ رایج
    بین نگارش عربی و فارسی و سبک تایپ کاربرها باعث «پیدا نشدن» نتیجه‌ی درست
    نشود. این تابع:
    - ابتدا normalize_input_text را اجرا می‌کند (ي/ك و کاراکترهای نامرئی)
    - اشکال مختلف الف (أ إ آ ٱ) را یکی می‌کند
    - ة را معادل ه در نظر می‌گیرد (چون کاربران معمولاً همان‌طور تایپ می‌کنند)
    - ؤ/ئ را به و/ی ساده تبدیل می‌کند
    - اعراب (فتحه/کسره/ضمه/تشدید/سکون/تنوین) و کشیدگی حروف را حذف می‌کند
    - علائم نگارشی را حذف و فاصله‌های اضافه را یکی می‌کند
    - خروجی را lower-case می‌کند (برای کلمات لاتین احتمالی)
    """
    if not text:
        return ""

    text = normalize_input_text(text)

    text = (
        text.replace("أ", "ا")
        .replace("إ", "ا")
        .replace("آ", "ا")
        .replace("ٱ", "ا")
        .replace("ة", "ه")
        .replace("ؤ", "و")
        .replace("ئ", "ی")
    )

    text = _DIACRITICS_RE.sub("", text)
    text = _TATWEEL_RE.sub("", text)
    text = _PUNCT_RE.sub(" ", text)
    text = _MULTISPACE_RE.sub(" ", text).strip()

    return text.lower()
