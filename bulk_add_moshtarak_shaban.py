import sqlite3
import os

def get_db_connection():
    # مسیر فایل دیتابیس ربات را بر اساس ساختار پروژه مشخص کنید
    db_path = "bot_database.db"
    if not os.path.exists(db_path):
        # تلاش برای پیدا کردن در پوشه بالاتر یا مجاور در صورت نیاز
        db_path = os.path.join(os.path.dirname(__file__), "bot_database.db")
    return sqlite3.connect(db_path)

def add_mafatih_item(slug, category, title, arabic_text, translation_text=None, audio_file_id=None):
    conn = get_db_connection()
    cursor = conn.cursor()
    try:
        # بررسی وجود آیتم از قبل
        cursor.execute("SELECT id FROM mafatih WHERE slug = ?", (slug,))
        row = cursor.fetchone()
        
        if row:
            # بروزرسانی در صورت وجود
            cursor.execute(
                """
                UPDATE mafatih 
                SET category = ?, title = ?, arabic_text = ?, translation_text = ?, audio_file_id = ?
                WHERE slug = ?
                """,
                (category, title, arabic_text, translation_text, audio_file_id, slug)
            )
            print(f"✅ آیتم با اسلاگ '{slug}' با موفقیت بروزرسانی شد.")
        else:
            # درج جدید در صورت عدم وجود
            cursor.execute(
                """
                INSERT INTO mafatih (slug, category, title, arabic_text, translation_text, audio_file_id)
                VALUES (?, ?, ?, ?, ?, ?)
                """,
                (slug, category, title, arabic_text, translation_text, audio_file_id)
            )
            print(f"✅ آیتم جدید با اسلاگ '{slug}' با موفقیت ثبت شد.")
            
        conn.commit()
    except Exception as e:
        print(f"❌ خطا در ثبت آیتم '{slug}': {e}")
        conn.rollback()
    finally:
        conn.close()

