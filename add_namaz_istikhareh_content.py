import database as db

TITLE = "استخاره ذات الرقاع"
SLUG = "namaz_istikhareh"
CATEGORY = "special"  # ذیل «نمازهای مستحب» در منوی باقیات صالحات

CONTENT = r"""
نحوه‌ی انجام «استخاره ذات الرّقاع» که از امام صادق(ع) نقل شده، به این شکل است که هرگاه برای امور مهمّی بخواهی استخاره کنی، بدین شیوه عمل کن:

نخست شش قطعه کاغذ تهیه می‌کنی. در سه قطعه از آن‌ها می‌نویسی:

بِسْمِ اللّهِ الرَّحْمنِ الرَّحیمِ، خِیَرَةً مِنَ اللّهِ الْعَزیزِ الحَکیمِ، لِفُلانِ بنِ فُلانَة اِفْعَل

«به نام خداوند بخشنده مهربان. اختیار و گزینشی است از جانب خداوند عزیز و حکیم برای فلانی فرزند فلانی» (به‌جای «فلان بن فلانه»، نام شخصی که برایش استخاره می‌کنی و نام مادرش را می‌نویسی).

در سه ورقه‌ی دیگر، همین عبارت را می‌نویسی، با این تفاوت که به‌جای «اِفْعَل» می‌نویسی «لا تَفْعَل».

سپس آن کاغذها را زیر جانماز/سجاده‌ی خود می‌گذاری و دو رکعت نماز می‌خوانی.

پس از نماز به سجده می‌روی و در سجده صد مرتبه می‌گویی:

أَستَخیرُ اللّهَ برَحْمَتِهِ، خِیَرَةً فی عافِیَة

«از رحمت الهی طلب خیر و سعادت همراه با عافیت می‌کنم»

سپس می‌نشینی و می‌گویی:

أللّهُمَّ خِرْ لی، وَاخْتَر لی فی جَمیعِ اُمُوری فی یُسْر وَ عافِیَة

«خدایا در همه‌ی امور، به آسانی و عافیت، خودت (آنچه را که صلاح است) برایم اختیار کن»

---

نحوه‌ی گزینش ورقه‌ها:

سپس دست می‌بری و آن ورقه‌ها را به هم مخلوط می‌کنی و یکی‌یکی بیرون می‌آوری:

- اگر سه ورقه‌ای که در آن‌ها «اِفْعَل» نوشته شده، پشت سر هم بیرون آمد، کاری را که نیت کرده‌ای انجام بده (بسیار خوب است).
- اگر سه ورقه‌ی «لا تَفْعَل» پیاپی بیرون آمد، آن کار را انجام نده.
- اگر یک‌بار «اِفْعَل» و بار بعد «لا تَفْعَل» به دست آمد (نتیجه مخلوط بود)، در این صورت سه ورقه‌ی دیگر را نیز بیرون بیاور تا در مجموع پنج ورقه خارج شود:
  - اگر از این پنج ورقه، سه‌تا «اِفْعَل» و دوتا «لا تَفْعَل» بود، آن کار را انجام بده.
  - اگر برعکس شد (سه‌تا «لا تَفْعَل» و دوتا «اِفْعَل»)، آن کار را انجام نده.

منبع: مفاتیح‌الجنان، بخش استخاره‌ها، استخاره‌ی ذات‌الرقاع (منقول از امام صادق علیه‌السلام).
""".strip()


def main():
    item_id = db.add_mafatih_item(
        category=CATEGORY,
        title=TITLE,
        arabic_text="",
        translation_text=CONTENT,
        slug=SLUG,
    )
    print(f"OK: mafatih item saved/updated. id={item_id}, slug={SLUG}")


if __name__ == "__main__":
    main()
