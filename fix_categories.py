def main():
    parser = argparse.ArgumentParser(description="اصلاح دسته‌بندی احادیث")
    parser.add_argument("--apply", action="store_true", help="اعمال واقعی تغییرات")
    parser.add_argument("--dry-run", action="store_true", help="فقط نمایش تغییرات")
    args = parser.parse_args()

    if not args.apply and not args.dry_run:
        print("لطفاً یکی از --dry-run یا --apply را مشخص کن.")
        return

    init_db()

    print(f"🔄 بررسی {len(CATEGORY_FIXES)} اصلاح پیشنهادی...\n")

    applied = 0
    skipped_same = 0
    not_found = 0

    for hadith_id, new_category in sorted(CATEGORY_FIXES.items()):
        row = get_hadith_by_id(hadith_id)
        if not row:
            print(f"⚠️  حدیث #{hadith_id} پیدا نشد (احتمالاً حذف شده) — رد شد.")
            not_found += 1
            continue

        old_category = row["category"]
        if old_category == new_category:
            skipped_same += 1
            continue

        preview = (row["translation_text"] or "")[:60]
        print(f"#{hadith_id}: {old_category}  →  {new_category}")
        print(f"    {preview}...")

        if args.apply:
            update_hadith_category(hadith_id, new_category)
        applied += 1

    print("\n" + "=" * 50)
    if args.apply:
        print(f"✅ {applied} حدیث اصلاح و ذخیره شد.")
    else:
        print(f"📋 حالت آزمایشی: {applied} حدیث نیاز به اصلاح دارند (چیزی ذخیره نشد).")
        print("   برای اعمال واقعی: python fix_categories.py --apply")
    if skipped_same:
        print(f"ℹ️  {skipped_same} مورد از قبل دسته‌ی درست را داشتند.")
    if not_found:
        print(f"⚠️  {not_found} مورد پیدا نشدند.")


if __name__ == "__main__":
    main()
