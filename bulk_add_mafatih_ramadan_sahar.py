def add_directly_to_sqlite():
    """ثبت مستقیم در فایل دیتابیس محلی (در صورتی که اسکریپت مستقل اجرا شود)"""
    db_candidates = ["bot.db", "database.sqlite", "database.db", "mafatih.db"]
    db_file = None
    
    for cand in db_candidates:
        if os.path.exists(cand):
            db_file = cand
            break
        elif os.path.exists(os.path.join("..", cand)):
            db_file = os.path.join("..", cand)
            break
            
    if not db_file:
        db_file = "bot.db"
        print(f"⚠️ فایل دیتابیس sqlite پیدا نشد. به طور پیش‌فرض روی '{db_file}' عملیات انجام می‌شود.")

    try:
        conn = sqlite3.connect(db_file)
        cursor = conn.cursor()
        
        cursor.execute("SELECT name FROM sqlite_master WHERE type='table' AND name='mafatih';")
        if not cursor.fetchone():
            cursor.execute("SELECT name FROM sqlite_master WHERE type='table' AND name='mafatih_items';")
            table_name = "mafatih_items" if cursor.fetchone() else "mafatih"
        else:
            table_name = "mafatih"
            
        print(f"ℹ️ جدول هدف شناسایی شد: {table_name}")
        
        cursor.execute(f"SELECT slug FROM {table_name} WHERE slug = ?;", ("ramadan_sahar",))
        exists = cursor.fetchone()
        
        if exists:
            query = f"""
                UPDATE {table_name} 
                SET category = ?, title = ?, arabic_text = ?, translation_text = NULL, audio_file_id = NULL
                WHERE slug = ?;
            """
            cursor.execute(query, ("month_ramadan", "اعمال سحر ماه مبارک رمضان", TEXT_CONTENT, "ramadan_sahar"))
            print(f"✅ [بروزرسانی مستقیم] رکورد 'ramadan_sahar' در جدول '{table_name}' با موفقیت آپدیت شد.")
        else:
            query = f"""
                INSERT INTO {table_name} (slug, category, title, arabic_text, translation_text, audio_file_id)
                VALUES (?, ?, ?, ?, NULL, NULL);
            """
            cursor.execute(query, ("month_ramadan", "month_ramadan", "اعمال سحر ماه مبارک رمضان", TEXT_CONTENT))
            print(f"✅ [درج مستقیم] رکورد جدید 'ramadan_sahar' در جدول '{table_name}' با موفقیت اضافه شد.")
            
        conn.commit()
        conn.close()
    except Exception as e:
        print(f"❌ خطا در عملیات مستقیم روی SQLite دیتابیس: {e}")

