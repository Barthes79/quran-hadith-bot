import sqlite3
from config import DATABASE_PATH

def fix_ghadir_final():
    """Fix Ghadir Khum - remove duplicates and simplify"""
    
    conn = sqlite3.connect(DATABASE_PATH)
    conn.row_factory = sqlite3.Row
    cur = conn.cursor()
    
    # بررسی وجود عید غدیر
    item = cur.execute("SELECT id, title FROM mafatih WHERE slug = 'ghadir_day'").fetchone()
    
    if not item:
        print("❌ عید غدیر در دیتابیس پیدا نشد!")
        conn.close()
        return False
    
    print(f"✅ عید غدیر پیدا شد! ID: {item['id']}")
    
    # ============================================
    # متن جدید - خلاصه و بدون تکرار
    # ============================================
    new_full_text = """✨ **اعمال عید غدیر خم (۱۸ ذی‌الحجه)**

**👑 عید غدیر خم**

عید غدیر خم، بزرگ‌ترین عید مسلمانان است. در این روز، پیامبر اکرم (ص) در غدیر خم، حضرت علی (ع) را به عنوان جانشین خود معرفی کرد.

**«مَنْ کُنْتُ مَوْلاهُ فَهذا عَلِیٌّ مَوْلاهُ»**

---

**🌟 اعمال عید غدیر خم:**

**۱. غسل کردن** - مستحب مؤکد

**۲. پوشیدن لباس نو و معطر بودن**

**۳. نماز شب عید غدیر (۱۲ رکعت)**
هر دو رکعت یک تشهد دارد.
- در هر رکعت: حمد + ۱۰ بار توحید + ۱ بار آیة الکرسی

**۴. نماز روز عید غدیر (۲ رکعت)**
نیم ساعت قبل از ظهر: حمد + ۱۰ بار توحید + ۱۰ بار قدر + ۱۰ بار آیة الکرسی

**۵. روزه گرفتن** - برابر با ۱۰۰ حج و ۱۰۰ عمره

**۶. زیارت امیرالمؤمنین (ع)** - زیارت امین الله

**۷. تبریک و تهنیت** - گفتن ذکر مخصوص

**۸. شادی کردن و زینت دادن**

**۹. ذکر صلوات بسیار**

**۱۰. دید و بازدید عید**

**۱۱. هدیه دادن**

**۱۲. طعام دادن به مؤمنان**

**۱۳. کمک به نیازمندان و رفع حاجات**

**۱۴. صدقه دادن** - هر درهم = ۲۰۰,۰۰۰ درهم

**۱۵. نیکی و احسان**

**۱۶. لبخند زدن و گشاده رویی**

---

**📝 فضیلت عید غدیر:**

امام رضا (ع) فرمود: "إِنَّ اللَّهَ یُعْتِقُ فِی هَذَا الْیَوْمِ ضِعْفَ مَا یُعْتِقُ فِی شَهْرِ رَمَضَانَ وَ لَیْلَةِ الْقَدْرِ"

خداوند در این روز دو برابر شب قدر و عید فطر، بندگان را از آتش آزاد می‌کند.

امام رضا (ع) فرمود: "هُوَ الْیَوْمُ الَّذِی یَزِیدُ اللَّهُ فِی مَالِ مَنْ عَبَدَ اللَّهَ وَ وَسَّعَ عَلَی عِیَالِهِ"

روز غدیر روزی است که خداوند در مال کسی که خدا را عبادت کند و بر خانواده خود توسعه دهد، برکت قرار می‌دهد."""

    # ============================================
    # توضیحات - خلاصه نهایی
    # ============================================
    new_tafsir_text = """📖 **خلاصه اعمال عید غدیر خم**

**عید غدیر خم** در ۱۸ ذی‌الحجه برگزار می‌شود.

**اعمال اصلی (۱۶ مورد):**

۱. غسل
۲. لباس نو و عطر
۳. نماز شب (۱۲ رکعت)
۴. نماز روز (۲ رکعت)
۵. روزه (۱۰۰ حج و ۱۰۰ عمره)
۶. زیارت امیرالمؤمنین
۷. تبریک و تهنیت
۸. شادی و زینت
۹. صلوات
۱۰. دید و بازدید
۱۱. هدیه
۱۲. اطعام
۱۳. کمک به نیازمندان
۱۴. صدقه
۱۵. نیکی و احسان
۱۶. لبخند و گشاده رویی

**روایات:**
- پیامبر (ص): «مَنْ کُنْتُ مَوْلاهُ فَهذا عَلِیٌّ مَوْلاهُ»
- امام رضا (ع): روز غدیر روز برکت است"""

    # ============================================
    # بروزرسانی
    # ============================================
    try:
        cur.execute("""
            UPDATE mafatih 
            SET arabic_text = ?, tafsir_text = ?
            WHERE slug = 'ghadir_day'
        """, (new_full_text, new_tafsir_text))
        
        conn.commit()
        
        print("✅ عید غدیر با موفقیت اصلاح و خلاصه شد!")
        print("   - متن اصلی کوتاه و مفید شد")
        print("   - توضیحات به صورت خلاصه است")
        print("   - تکرارها حذف شدند")
        
        conn.close()
        return True
        
    except Exception as e:
        print(f"❌ خطا: {e}")
        conn.close()
        return False

if __name__ == "__main__":
    fix_ghadir_final()