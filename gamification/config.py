def fridge_upgrade_cost(level: int) -> int:
    """هزینه‌ی ارتقا از این سطح به سطح بعد. سطح ۱→۲ دقیقاً همون ۲۰۰,۰۰۰ست."""
    return int(round(FRIDGE_UPGRADE_BASE_COST * (FRIDGE_UPGRADE_GROWTH ** (level - 1))))


