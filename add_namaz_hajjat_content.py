"""
اسکریپت افزودن «نماز حاجت» به دیتابیس مفاتیح‌الجنان.

نحوه استفاده:
    این فایل را کنار database.py و config.py پروژه ربات قرار دهید و اجرا کنید:

        python add_namaz_hajjat_content.py

    آیتمی با category="special" و slug="namaz_hajjat" درج/به‌روزرسانی می‌شود.
    این slug همان چیزی است که دکمه‌ی "🤲 نماز حاجت"
    (callback_data="mafitem_namaz_hajjat") در mafatih.py به آن ارجاع می‌دهد،
    پس بلافاصله در منوی «نمازهای مستحب» ربات قابل مشاهده خواهد بود.
"""

import database as db

TITLE = "نماز حاجت"
SLUG = "namaz_hajjat"
CATEGORY = "special"  # ذیل «نمازهای مستحب» در منوی باقیات صالحات

CONTENT = r"""
شیوه‌ی خواندن این نماز، از کتاب «جمال‌الاسبوع» سید بن طاووس نقل شده است.

این نماز چهار رکعت است (دو نماز دورکعتی):

رکعت اول: بعد از سوره حمد، ۱۱ بار سوره توحید.
رکعت دوم: بعد از حمد، ۲۱ بار سوره توحید.

(سلام نماز اول داده می‌شود، سپس نماز دوم آغاز می‌شود:)

رکعت سوم: بعد از حمد، ۳۱ بار سوره توحید.
رکعت چهارم: بعد از حمد، ۴۱ بار سوره توحید.

بعد از سلام نماز دوم:

- ۵۱ بار سوره توحید خوانده شود.
- ۵۱ بار «اللَّهُمَّ صَلِّ عَلَى مُحَمَّدٍ وَ آلِ مُحَمَّد» گفته شود.

سپس به سجده برود و ۱۰۰ بار بگوید «یاالله، یاالله»، و آنگاه هرچه می‌خواهد از خداوند درخواست کند.

---

فضیلت این نماز:

پیامبر اکرم(ص) فرمودند: اگر کسی از خدا بخواهد که کوهی را نابود کند، کوه نابود می‌شود؛ اگر نزول باران را بخواهد، به‌یقین باران نازل می‌شود؛ همانا هیچ‌چیز میان او و خداوند مانع نمی‌شود. خداوند متعال بر کسی که این نماز را بخواند و حاجتش را از او نخواهد، خشم می‌گیرد.
""".strip()


def main():
    item_id = db.add_mafatih_item(
        category=CATEGORY,
        title=TITLE,
        arabic_text="",
        translation_text=CONTENT,
        slug=SLUG,
    )
    print(f"OK: mafatih item saved/updated. id={item_id}, slug={SLUG}")


if __name__ == "__main__":
    main()
